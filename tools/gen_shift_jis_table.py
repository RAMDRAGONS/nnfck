#!/usr/bin/env python3
"""Writes src/core/shift_jis_table.inc: the CP932 double-byte table, one
UTF-16 code unit per lead and trail byte pair, 0 where the pair is undefined
or user-defined."""

import pathlib

LEADS = [*range(0x81, 0xA0), *range(0xE0, 0xFD)]
TRAILS = range(0x40, 0xFD)


def code_unit(lead: int, trail: int) -> int:
    try:
        text = bytes([lead, trail]).decode("cp932")
    except UnicodeDecodeError:
        return 0
    cp = ord(text) if len(text) == 1 else 0
    return 0 if 0xE000 <= cp <= 0xF8FF else cp


def main() -> None:
    units = [code_unit(lead, trail) for lead in LEADS for trail in TRAILS]
    lines = [
        "// Generated by tools/gen_shift_jis_table.py from Python's cp932 codec.",
        "// Indexed by lead byte slot * 189 + (trail byte - 0x40).",
    ]
    for i in range(0, len(units), 12):
        lines.append(" ".join(f"0x{u:04X}," for u in units[i : i + 12]))
    out = pathlib.Path(__file__).resolve().parent.parent / "src/core/shift_jis_table.inc"
    out.write_text("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
